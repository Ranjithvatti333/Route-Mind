import type { Stop, TransitRoute, TransitBus, NetworkMapRoute } from "@/lib/types";
import { COORDS } from "./network";

function stops(names: string[]): Stop[] {
  return names.map((name, i) => ({
    id: `${name}-${i}`,
    name: name.replace(/(^|-)([a-z])/g, (m) => m.toUpperCase()).replace(/-/g, " "),
    lat: COORDS[name][0],
    lng: COORDS[name][1],
    sequence: i + 1,
  }));
}

